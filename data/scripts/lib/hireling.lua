-- The NPC type's key never changes; only its display name does. That is what
-- makes a rename possible from a network handler at all: Game.createNpcType
-- refuses to run outside the Scripts/Npc interfaces (the previous version
-- built a NEW type per rename and every rename failed with exactly that
