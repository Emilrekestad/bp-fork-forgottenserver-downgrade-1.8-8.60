local function addHirelingLampToInbox(player, hireling)
	local inbox = player and player:getStoreInbox()
	if not inbox then
		return nil
	end

	local lamp = inbox:addItem(HIRELING_LAMP, 1, INDEX_WHEREEVER, FLAG_NOLIMIT)
	if not lamp then
		return nil
	end

	return decorateHirelingLamp(lamp, hireling)
end

-- Hand the lamp over directly, for an NPC giving it to you face to face.
--
-- The lamp is `movable="0"`, so it can never be a chest reward -- the player
-- would not be able to pick it up. It also is not a generic item: each lamp
-- carries a custom attribute naming one database row, and a lamp without that
-- attribute deletes itself with an error when used. So a quest has to CREATE
-- the hireling and hand over the lamp it gets back, which is what
-- Player:addNewHireling does.
--
-- Falls back to the Store Inbox when the backpack cannot take it, so a full
-- or overloaded player never loses a quest reward.
local function addHirelingLampToPlayer(player, hireling)
	local lamp = player:addItem(HIRELING_LAMP, 1)
	if lamp then
		return decorateHirelingLamp(lamp, hireling), "backpack"
	end

	local inboxLamp = addHirelingLampToInbox(player, hireling)
	if inboxLamp then
		return inboxLamp, "inbox"
	end
	return nil
end

local function persistHirelingReturn(owner, hireling)
	local previousState = {
		active = hireling.active,
		cid = hireling.cid,
		position = {
			x = hireling.posx,
			y = hireling.posy,
			z = hireling.posz
		}
	}
	local lamp
	local committed = false
	local failureReason = "Failed to return the hireling to its lamp."

	local ok, err = pcall(function()
		lamp = addHirelingLampToInbox(owner, hireling)
		if not lamp then
			failureReason = "You don't have enough room in your store inbox."
			return
		end

		hireling.active = 0
		hireling.cid = -1
		hireling:setPosition({ x = 0, y = 0, z = 0 })

		if not hireling:save() then
			return
		end

		if not owner.save or not owner:save() then
			return
		end

		committed = true
	end)

	if committed then
		return true
	end

	local lampRollbackOk = pcall(function()
		if lamp and lamp.remove then
			lamp:remove()
		end
	end)
	local stateRollbackOk = pcall(function()
		hireling.active = previousState.active
		hireling.cid = previousState.cid
		hireling:setPosition(previousState.position)
	end)

	local hirelingRollbackOk, hirelingRollbackResult = pcall(function()
		return hireling:save()
	end)
	local ownerRollbackOk, ownerRollbackResult = pcall(function()
		return owner.save and owner:save()
	end)

	if not lampRollbackOk or not stateRollbackOk or not hirelingRollbackOk or not hirelingRollbackResult or
		not ownerRollbackOk or not ownerRollbackResult then
		logError("[Hireling] Failed to persist rollback while returning hireling id " .. tostring(hireling:getId()) .. ".")
	end
	if not ok then
		logError("[Hireling] Failed to return hireling id " .. tostring(hireling:getId()) .. ": " .. tostring(err))
	end
	return false, failureReason
end

-- One NPC type per hireling, keyed by Hireling:getSpawnKey(). The type is
-- registered ONCE (Game.createNpcType only works from the Scripts or Npc
-- interface, so it has to happen at startup or from the lamp action) and its
-- display name is changed in place on rename -- see Hireling:renameForCoins.
HIRELING_NPC_TYPES = HIRELING_NPC_TYPES or {}

local function ensureHirelingNpcType(npcName, displayName)
	if HIRELING_NPC_TYPES[npcName] then
		return true
	end

	if not createHirelingType then
		local ok, err = pcall(dofile, "data/npc/crystalserver/shops/mixed/hireling.lua")
		if not ok then
			logError("[Hireling] Failed to load Crystal hireling NPC: " .. tostring(err))
			return false
		end
	end

	if not createHirelingType then
		logError("[Hireling] createHirelingType is not available.")
		return false
	end

	local ok, err = pcall(createHirelingType, npcName, displayName)
	if not ok then
		logError("[Hireling] Failed to register NPC type " .. npcName .. ": " .. tostring(err))
		return false
	end
	return true
end

-- `active` in player_hirelings: 0 in his lamp, 1 standing in a house, and 2
-- "in his lamp, but the lamp is still owed". The third state exists because
-- a hireling can have to leave the house while his owner is OFFLINE (the
-- house changed hands, or the house check failed at startup), and an offline
-- player has no Store Inbox to put a lamp into. Before this state existed
-- the return simply failed, the row stayed at 1 with no creature and no
-- lamp anywhere, and the owner had no way to get him back. The lamp is
-- delivered by Player:claimOwedHirelingLamps() on the owner's next login.
HIRELING_ACTIVE_LAMP_OWED = 2

local function parkHirelingLampOwed(hireling, why)
	local npc = hireling.cid and hireling.cid > 0 and Npc(hireling.cid) or nil
	hireling.active = HIRELING_ACTIVE_LAMP_OWED
	hireling.cid = -1
	hireling:setPosition({ x = 0, y = 0, z = 0 })
	if not hireling:save() then
		logError("[Hireling] Could not park hireling id " .. tostring(hireling:getId()) .. " (" .. tostring(why) .. ").")
		return false
	end
	if npc then
		npc:remove()
	end
	logWarning("[Hireling] Hireling id " .. tostring(hireling:getId()) .. " (" .. hireling:getName() ..
		") sent to his lamp while the owner is offline: " .. tostring(why) .. ". Lamp owed on next login.")
	return true
end

local function returnHirelingToOwnerInbox(hireling, why)
	if not hireling then
		return false
	end

	local owner = Player(hireling:getOwnerId())
	if not owner then
		return parkHirelingLampOwed(hireling, why)
	end

	local npc = hireling.cid and Npc(hireling.cid) or nil
	local returned = persistHirelingReturn(owner, hireling)
	if not returned then
		-- Online but no room in the inbox: park him, the login/claim path
		-- retries. Losing the creature beats stranding the row at active=1.
		return parkHirelingLampOwed(hireling, tostring(why) .. "; inbox delivery failed")
	end

	if npc then
		npc:remove()
	end
	owner:sendTextMessage(MESSAGE_EVENT_ADVANCE, hireling:getName() .. " has returned to the lamp in your Store Inbox.")
	return true
end

local function checkHouseAccess(hireling)
	if not hireling or hireling.active ~= 1 then
		return false
	end

	local position = hireling:getPosition()
	local tile = position:getTile()
	local house = tile and tile:getHouse()
	if not house then
		returnHirelingToOwnerInbox(hireling, "no house at " .. tostring(position))
		return false
	end

	if house:getOwnerGuid() == hireling:getOwnerId() then
		return true
	end

	returnHirelingToOwnerInbox(hireling, string.format("house %d owned by %d, hireling owned by %d",
		house:getId(), house:getOwnerGuid(), hireling:getOwnerId()))
	return false
end

local function spawnHirelings()
	if not hirelingSystemEnabled() then
		return
	end

	for _, hireling in ipairs(HIRELINGS) do
		if checkHouseAccess(hireling) then
			hireling:spawn()
		end
	end
end

