-- 100 BPC (owner, 2026-10-04; 25 before, 10 before that). A name is the one thing about a
-- hireling everyone else sees, and the price should say so.
HIRELING_RENAME_COST = 100

function Hireling:renameForCoins(player, name)
	if self:getOwnerId() ~= player:getGuid() or not self:canTalkTo(player) or self._returning then
		return false, "Only the owner can rename this hireling."
	end
	name = formatHirelingName(name)
	if not isValidHirelingName(name) then return false, "Use 3 to 20 letters, with single spaces between words." end
	if name == self.name then return false, "That is already my name. No coins were spent." end

	local oldNpc = Npc(self.cid)
	local npcType = HIRELING_NPC_TYPES[self:getSpawnKey()]
	if not oldNpc or not npcType then return false, "Unable to change the name. No coins were spent." end

	local oldName = self.name
	local ok = Coins.move(player:getAccountId(), -HIRELING_RENAME_COST, "spend.hireling_name",
		{type = "hireling", id = self:getId()}, {oldName = oldName, newName = name}, player:getGuid(), function()
			if not db.query("UPDATE `player_hirelings` SET `name`=" .. db.escapeString(name) ..
				" WHERE `id`=" .. self:getId() .. " AND `player_id`=" .. player:getGuid()) or db.affectedRows() ~= 1 then
				error("Hireling name update failed")
			end
		end)
	if not ok then
		return false, string.format("Renaming costs %d BPC. The payment could not be completed; no name change was made.", HIRELING_RENAME_COST)
	end

	-- Paid and persisted. A creature's name is copied from its type when it is
	-- created, so rename the type and stand up a fresh creature; the old one
	-- goes once the new one exists, so he is never absent from the house.
	self.name = name
	npcType:name(name)
	local replacement = Game.createNpc(self:getSpawnKey(), self:getPosition(), false, true, CONST_ME_NONE)
	if not replacement then
		-- Persisted under the new name; he answers to it after the next
		-- summon or server save. Not worth refunding over.
		logWarning("[Hireling] Renamed hireling " .. self:getId() .. " but could not respawn the creature.")
		return true
	end
	replacement:setOutfit(self:getOutfit())
	replacement:setSpeechBubble(SPEECHBUBBLE_HIRELING or 7)
	self:setCreature(replacement)
	oldNpc:remove()
	return true
end

function Hireling:canTalkTo(player)
	if not player or self.active ~= 1 then
		return false
	end

	if Position.getDistanceBetween(player:getPosition(), self:getPosition()) > 3 then
		return false
	end

	local playerTile = player:getPosition():getTile()
	local playerHouse = playerTile and playerTile:getHouse()
	local hirelingTile = self:getPosition():getTile()
	local hirelingHouse = hirelingTile and hirelingTile:getHouse()
	return playerHouse and hirelingHouse and playerHouse:getId() == hirelingHouse:getId()
end

