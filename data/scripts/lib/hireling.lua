function Player:sendHirelingOutfitWindow(hireling)
	if not astraHirelingProtocolEnabled(self) or not hireling then
		return false
	end

	local outfit = hireling:getOutfit()
	local msg = NetworkMessage()
	msg:addByte(0xC8)
	msg:addU16(outfit.lookType)
	if outfit.lookType == 0 then
		msg:addU16(outfit.lookTypeEx or 0)
	else
		msg:addByte(outfit.lookHead)
		msg:addByte(outfit.lookBody)
		msg:addByte(outfit.lookLegs)
		msg:addByte(outfit.lookFeet)
		msg:addByte(outfit.lookAddons)
	end
	msg:addU16(outfit.lookMount or 0)
	msg:addU16(0) -- familiar looktype (Astra outfit extension)

	local availableOutfits = hireling:getAvailableOutfits(true)
	msg:addByte(math.min(#availableOutfits, 255))
	local storeOffers = {}
	for i = 1, math.min(#availableOutfits, 255) do
		local outfitData = availableOutfits[i]
		msg:addU16(outfitData.lookType)
		msg:addString(outfitData.name)
		msg:addByte(0)
		if outfitData.storeOffer and outfitData.storeOffer > 0 then
			storeOffers[#storeOffers + 1] = { outfitData.lookType, outfitData.storeOffer }
		end
	end

	msg:addByte(0) -- mount count

	msg:addByte(0x48) -- H
	msg:addByte(0x52) -- R
	msg:addByte(0x4C) -- L
	msg:addByte(0x47) -- G
	msg:addU32(hireling.cid > 0 and hireling.cid or 0)
	msg:addByte(hireling.sex)
	msg:addU16(math.min(#storeOffers, 255))
	for i = 1, math.min(#storeOffers, 255) do
		msg:addU16(storeOffers[i][1])
		msg:addU32(storeOffers[i][2])
	end
	msg:addByte(0) -- try-on pair count

	return msg:sendToPlayer(self)
end

-- Deliver every lamp this character is owed (see HIRELING_ACTIVE_LAMP_OWED).
-- Also heals the older failure mode directly: a row at active=1 with no
-- creature behind it after startup is a hireling nobody can reach, so he is
-- treated as owed too. Returns how many lamps were handed over.
function Player:claimOwedHirelingLamps()
	local delivered = 0
	for _, hireling in ipairs(self:getHirelings()) do
		local stranded = hireling.active == 1 and (not hireling.cid or hireling.cid <= 0 or not Npc(hireling.cid))
		if hireling.active == HIRELING_ACTIVE_LAMP_OWED or stranded then
			if self:findHirelingLamp(hireling:getId()) then
				-- Already has a lamp in the inbox (a half-completed return); just fix the row.
				hireling.active = 0
				hireling.cid = -1
				hireling:setPosition({ x = 0, y = 0, z = 0 })
				hireling:save()
			else
				local lamp = addHirelingLampToInbox(self, hireling)
				if lamp then
					hireling.active = 0
					hireling.cid = -1
					hireling:setPosition({ x = 0, y = 0, z = 0 })
					if hireling:save() then
						delivered = delivered + 1
						self:sendTextMessage(MESSAGE_EVENT_ADVANCE, hireling:getName() .. "'s lamp has been placed in your Store Inbox.")
					else
						lamp:remove()
						logError("[Hireling] Could not save hireling id " .. tostring(hireling:getId()) .. " after delivering an owed lamp.")
					end
				else
					self:sendTextMessage(MESSAGE_FAILURE, "Your Store Inbox is full, so " .. hireling:getName() .. "'s lamp could not be delivered. Make room and relog.")
				end
			end
		end
	end
	return delivered
end

function Player:findHirelingLamp(hirelingId)
	local inbox = self:getStoreInbox()
	if not inbox then
		return nil
	end

	for i = 0, inbox:getSize() - 1 do
		local item = inbox:getItem(i)
		if item and item:getId() == HIRELING_LAMP and item:getCustomAttribute("Hireling") == hirelingId then
			return item
		end
	end
	return nil
end

-- Kept for callers that ask "does this character have a hireling who can do X"
-- rather than asking about one hireling. Jobs themselves live per hireling
-- (see Hireling:hasSkill), so this is an ANY across the character's hirelings.
function Player:hasHirelingSkill(skillName)
	for _, hireling in ipairs(self:getHirelings()) do
		if hireling:hasSkill(skillName) then
			return true
		end
	end
	return false
end

function Player:hasHirelingOutfit(outfitName)
	return self:kv():scoped("hireling-outfits"):get(outfitName) == true
end

function Player:enableHirelingOutfit(outfitName)
	local outfitScoped = self:kv():scoped("hireling-outfits")
	if outfitScoped:get(outfitName) then
		return false
	end
	outfitScoped:set(outfitName, true)
	return true
end

function Player:clearAllHirelingStats()
	-- Jobs and signs are per hireling now, so clear each one's scope rather
	-- than a single shared list.
	local skillsScoped = self:kv():scoped("hireling-skills")
	local signsScoped = self:kv():scoped("hireling-signs")
	local wornScoped = self:kv():scoped("hireling-worn-signs")
	for _, hireling in ipairs(self:getHirelings()) do
		local id = tostring(hireling:getId())
		local hirelingScope = skillsScoped:scoped(id)
		for _, skill in pairs(HIRELING_SKILLS) do
			hirelingScope:set(skill[2], false)
		end

		local signScope = signsScoped:scoped(id)
		for _, sign in ipairs(HIRELING_SIGNS) do
			if sign.item ~= 0 then
				signScope:set(sign.key, false)
			end
		end
		wornScoped:scoped(id):set("sign", "none")
	end

	local outfitsScoped = self:kv():scoped("hireling-outfits")
	for _, outfit in pairs(HIRELING_OUTFITS) do
		outfitsScoped:set(outfit[2], false)
	end
end
