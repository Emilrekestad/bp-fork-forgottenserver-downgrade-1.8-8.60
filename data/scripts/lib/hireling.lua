-- ─────────────────────────── name signs ───────────────────────────
--
-- Purely cosmetic, and deliberately narrow: a sign restyles the line the world
-- draws over ONE hireling's head and nothing else. The battle list builds its
-- own label from the creature's name, so it keeps the plain name for free --
-- which is exactly the ask: different in the house, the same everywhere else.
--
-- Two client calls do the whole job, and both are already bound to Lua
-- (src/client/luafunctions_client.cpp), so no binary rebuild is involved:
--
--   Creature:setTitle(ornament, font, colour)  -- an extra line ABOVE the name
--   Creature:setInformationColor(colour)       -- the name's own colour
--
-- (!) The ornaments are ASCII on purpose. Creature text is drawn with the
-- client's bitmap cp1252 font sheets, and anything outside them draws as a
-- gap rather than as a glyph.
--
-- `colour` is the ink the NAME is written in, chosen to sit legibly on that
-- plaque's face rather than to be pretty on its own -- pale on the dark
-- materials, warm on the light ones.
--
-- (!) The client hides the engine's own name (alpha 0) and writes the name
-- into the plaque instead, so this colour is NOT setInformationColor's old
-- job of tinting the name and the health bar together. NPC health bars are
-- switched off outright now; see GameHideNpcNames in the client module.
--
-- A sign is bought as an ITEM and used on ONE hireling, exactly like a job
-- contract: the right to wear it belongs to that hireling and to no other,
-- so giving Bella the oak board leaves Rufus as he was. Dresses are still
-- per character, because those are bought once and shared -- the difference is
-- deliberate and it is the difference between a wardrobe and a contract.
--
-- `item` is the physical sign, and `plaque` names the picture the client
-- hangs: modules/game_hireling/hireling.lua turns it into
-- /images/game/hirelings/plaque_<plaque>.png, generated by
-- tools/gen_hireling_plaques.js. The two must agree, and
-- tools/test_hireling_store.lua checks that every key here has an image.
