function Hireling:getAvailableOutfits(includeLocked)
	local player = Player(self:getOwnerId())
	local sex = self.sex == HIRELING_SEX.FEMALE and "female" or "male"
	-- Each entry carries BOTH sexes' look types so the wardrobe can preview a
	-- dress on either build and switch sex without a second round trip.
	-- `lookType` is the one for the hireling's current sex.
	local outfitsAvailable = {
		{ name = HIRELING_OUTFIT_DEFAULT.name, lookType = HIRELING_OUTFIT_DEFAULT[sex],
			female = HIRELING_OUTFIT_DEFAULT.female, male = HIRELING_OUTFIT_DEFAULT.male, storeOffer = 0 },
	}

	if not player then
		return outfitsAvailable
	end

	for _, key in ipairs(HIRELING_OUTFIT_ORDER) do
		local outfitInfo = HIRELING_OUTFITS[key]
		local outfitName = outfitInfo and outfitInfo[2]
		local outfitTable = HIRELING_OUTFITS_TABLE[key]
		if outfitName and outfitTable then
			local haveOutfit = player:kv():scoped("hireling-outfits"):get(outfitName) == true
			if haveOutfit or includeLocked then
				outfitsAvailable[#outfitsAvailable + 1] = {
					name = outfitTable.name,
					lookType = outfitTable[sex],
					female = outfitTable.female,
					male = outfitTable.male,
					storeOffer = haveOutfit and 0 or (HIRELING_OUTFIT_STORE_OFFERS[outfitName] or 0),
				}
			end
		end
	end
	return outfitsAvailable
end

-- Everything the wardrobe can change, applied together: sex, dress and the
-- four colours. `lookType` must be the requested sex's look of a dress the
-- owner has (the citizen outfit is always owned). Returns false plus a
-- reason the hireling can say out loud.
function Hireling:setAppearance(player, sex, lookType, colours)
	if not player or self:getOwnerId() ~= player:getGuid() or not self:canTalkTo(player) then
		return false, "Only my master may dress me."
	end
	if sex ~= HIRELING_SEX.FEMALE and sex ~= HIRELING_SEX.MALE then
		return false, "I do not know that shape."
	end

	local dress
	for _, outfitData in ipairs(self:getAvailableOutfits(true)) do
		local matches = outfitData.female == lookType or outfitData.male == lookType
		if matches and (outfitData.storeOffer or 0) == 0 then
			dress = outfitData
			break
		elseif matches then
			return false, "I do not own that dress. You can buy dresses for me in the store."
		end
	end
	if not dress then
		return false, "I do not own that dress."
	end

	local outfit = self:getOutfit()
	outfit.lookType = sex == HIRELING_SEX.FEMALE and dress.female or dress.male
	for _, key in ipairs({ "lookHead", "lookBody", "lookLegs", "lookFeet" }) do
		local value = tonumber(colours and colours[key]) or outfit[key]
		if value < 0 or value > 132 then
			return false, "That is not a colour I know."
		end
		outfit[key] = value
	end

	local creature = Creature(self.cid)
	if not creature then
		return false, "I cannot change right now."
	end

	self.sex = sex
	creature:setOutfit(outfit)
	self:setOutfit(outfit)
	self:save()
	return true
end

-- The OWNER's kv scope, reached by GUID rather than through a Player object.
--
-- kv.scoped("player"):scoped(guid) is byte-for-byte the scope player:kv()
-- builds in C++ (luaPlayerKV: KVStore "player" -> fmt "{}" of the GUID), and
-- KVStore::get loads any key from `kv_store` on a cache miss -- so this reads
-- an OFFLINE owner's values exactly, with no character load at all.
--
-- (!) "%d", not tostring: C++ writes the GUID segment as an integer, and in
-- Lua 5.5 tostring of a float GUID is "123.0" -- a different key, read as
-- empty. The hireling-id segment below keeps tostring because that is how
-- every key already in the store was written.
local function ownerKV(ownerGuid)
	return kv.scoped("player"):scoped(string.format("%d", ownerGuid))
end

-- Signs live under the OWNER's kv keyed by hireling id, the same shape jobs
-- and the workshop use, because a hireling has no kv of its own. Two scopes:
-- which signs this hireling has been GIVEN, and which one he is WEARING.
local function hirelingSignStore(ownerGuid, hirelingId)
	return ownerKV(ownerGuid):scoped("hireling-worn-signs"):scoped(tostring(hirelingId))
end

local function hirelingSignRights(ownerGuid, hirelingId)
	return ownerKV(ownerGuid):scoped("hireling-signs"):scoped(tostring(hirelingId))
end

-- Does this hireling have the right to wear that sign? Granted by using the
-- sign item on him -- see data/scripts/actions/items/hireling_signs.lua.
function Hireling:hasSign(signKey)
	local sign = HIRELING_SIGNS_BY_KEY[signKey]
	if not sign then
		return false
	end
	if sign.plaque == "" then
		return true -- "No sign" is not something you buy
	end

	return hirelingSignRights(self:getOwnerId(), self:getId()):get(signKey) == true
end

-- Returns false when he already had it, so the caller can refuse to consume
-- the item before it is spent -- the same contract the job contracts keep.
function Hireling:grantSign(player, signKey)
	if not player or self:getOwnerId() ~= player:getGuid() then
		return false
	end
	local sign = HIRELING_SIGNS_BY_KEY[signKey]
	if not sign or sign.item == 0 then
		return false
	end

	local store = hirelingSignRights(self:getOwnerId(), self:getId())
	if store:get(signKey) == true then
		return false
	end
	store:set(signKey, true)
	return true
end

-- Every sign this hireling may wear, "No sign" first. The window sends this so
-- the wardrobe picker lists exactly what he can actually be given.
function Hireling:getSigns()
	local out = {}
	for _, sign in ipairs(HIRELING_SIGNS) do
		out[#out + 1] = { sign = sign, owned = self:hasSign(sign.key) }
	end
	return out
end

-- Read straight from the store by the owner's GUID, and NOT cached.
--
-- (!) This used to load the owner through getOwnerPlayer -- the whole
-- character, from the database, whenever he was offline -- and because that
-- was expensive the answer was memoised on the Lua object for the rest of the
-- boot. Any read that came back without a player cached 0, and nothing but a
-- fresh setSign ever cleared it. Signs are read for every hireling whenever
-- ANYONE logs in, so after a restart the first player in decided every sign
-- in the world. Owner-reported 2026-09-11 as "the plaque is lost on relog":
-- Sorcerer Harding logged in three times after the 07:20 boot before GM
-- Harding, King Winston's owner, did.
--
-- With the load gone there is nothing left worth caching: a KV get is an
-- in-memory lookup after its first miss.
function Hireling:getSignId()
	local key = hirelingSignStore(self:getOwnerId(), self:getId()):get("sign")
	local sign = type(key) == "string" and HIRELING_SIGNS_BY_KEY[key]
	return sign and sign.id or 0
end

-- Owner-only, and refuses a sign the character has not bought. Returns false
-- plus a reason the hireling can say out loud.
function Hireling:setSign(player, signId)
	if not player or self:getOwnerId() ~= player:getGuid() or not self:canTalkTo(player) then
		return false, "Only my master may choose my sign."
	end

	local sign = GetHirelingSign(signId)
	if not sign then
		return false, "I do not know that sign."
	end
	if not self:hasSign(sign.key) then
		return false, "Nobody has given me that sign. Use one on me and I will hang it."
	end

	hirelingSignStore(self:getOwnerId(), self:getId()):set("sign", sign.key)
	return true
end

function Hireling:requestOutfitChange()
	local player = Player(self:getOwnerId())
	if not player then
		return false
	end

	HIRELING_OUTFIT_CHANGING[self:getOwnerId()] = self:getId()
	return player:sendHirelingOutfitWindow(self)
end

function Hireling:hasOutfit(lookType)
	for _, outfit in ipairs(self:getAvailableOutfits(false)) do
		if outfit.lookType == lookType then
			return true
		end
	end
	return false
end

function Hireling:setOutfit(outfit)
	self.looktype = outfit.lookType
	self.lookhead = outfit.lookHead
	self.lookbody = outfit.lookBody
	self.looklegs = outfit.lookLegs
	self.lookfeet = outfit.lookFeet
end

function Hireling:changeOutfit(player, outfit)
	HIRELING_OUTFIT_CHANGING[self:getOwnerId()] = nil
	if not player or self:getOwnerId() ~= player:getGuid() or not self:canTalkTo(player) then
		return false
	end

	if not self:hasOutfit(outfit.lookType) then
		return false
	end

	local creature = Creature(self.cid)
	if not creature then
		return false
	end

	creature:setOutfit(outfit)
	self:setOutfit(outfit)
	self:save()
	return true
end

-- Jobs are stored PER HIRELING, not per character.
--
-- They used to hang off the owner's kv directly, so one purchase taught every
-- hireling that character owned. That was defensible while jobs came from the
-- store as an account-wide unlock. It is wrong now that a job arrives as a
-- physical contract the player uses on one specific hireling: handing a
-- contract to Bella and watching Rufus learn to cook makes the item a lie.
--
-- The scope is still the OWNER's kv (hirelings have no kv of their own), just
-- keyed by hireling id underneath. Dresses stay per character on purpose --
-- those are bought in the store and apply to everyone you own.
local function hirelingSkillStore(ownerGuid, hirelingId)
	return ownerKV(ownerGuid):scoped("hireling-skills"):scoped(tostring(hirelingId))
end

-- By GUID for the same reason as Hireling:getSignId. This one is asked by the
-- DIALOGUE, so every visitor who talked to a hireling whose owner was offline
-- used to load that owner's whole character -- and then kick it.
function Hireling:hasSkill(skillName)
	return hirelingSkillStore(self:getOwnerId(), self:getId()):get(skillName) == true
end

-- Which shop categories this hireling will open, in ONE place: the dialogue,
-- the window's Goods list and the packet that greys its rows all ask here, so
-- what he says and what the window shows cannot drift apart.
--
-- "various" is his own odds and ends and is open to everyone, trade or no
-- trade -- that has always been true and is the reason Goods is never a fully
-- locked section. Everything else needs the trader's contract.
function Hireling:canSellCategory(category)
	category = tostring(category or ""):lower()
	if category == "" then
		return false
	end
	if category == "various" then
		return true
	end
	return self:hasSkill(HIRELING_SKILLS.TRADER[2])
end

-- Returns false when the hireling already had the job, so callers can tell a
-- wasted contract from a successful one before consuming the item.
function Hireling:enableSkill(skillName)
	local store = hirelingSkillStore(self:getOwnerId(), self:getId())
	if store:get(skillName) == true then
		return false
	end
	store:set(skillName, true)
	return true
end

function Hireling:setCreature(creature)
	if type(creature) == "number" then
		self.cid = creature
	elseif creature and creature.getId then
		self.cid = creature:getId()
	end
end

function Hireling:save()
	if self.id <= 0 then
		return false
	end

	local sql = "UPDATE `player_hirelings` SET"
	sql = sql .. " `name`=" .. db.escapeString(self.name)
	sql = sql .. ", `active`=" .. tostring(self.active)
	sql = sql .. ", `sex`=" .. tostring(self.sex)
	sql = sql .. ", `posx`=" .. tostring(self.posx)
	sql = sql .. ", `posy`=" .. tostring(self.posy)
	sql = sql .. ", `posz`=" .. tostring(self.posz)
	sql = sql .. ", `lookbody`=" .. tostring(self.lookbody)
	sql = sql .. ", `lookfeet`=" .. tostring(self.lookfeet)
	sql = sql .. ", `lookhead`=" .. tostring(self.lookhead)
	sql = sql .. ", `looklegs`=" .. tostring(self.looklegs)
	sql = sql .. ", `looktype`=" .. tostring(self.looktype)
	sql = sql .. " WHERE `id`=" .. tostring(self.id)
	return db.query(sql)
end

function Hireling:spawn()
	if not hirelingSystemEnabled() then
		return false
	end

	local npcName = self:getSpawnKey()
	if not ensureHirelingNpcType(npcName, self:getName()) then
		return false
	end

	-- The type may have been registered under an earlier name (a rename while
	-- he was in his lamp, or a server save in between); the creature copies
	-- the type's name, so make sure it is current before he appears.
	local npcType = HIRELING_NPC_TYPES[npcName]
	if npcType and npcType:name() ~= self:getName() then
		npcType:name(self:getName())
	end

	self.active = 1
	local npc = Game.createNpc(npcName, self:getPosition(), false, true, CONST_ME_NONE)
	if not npc then
		self.active = 0
		return false
	end

	npc:setOutfit(self:getOutfit())
	npc:setSpeechBubble(SPEECHBUBBLE_HIRELING or 7)
	npc:getPosition():sendMagicEffect(CONST_ME_TELEPORT)
	self:setCreature(npc)
	self:save()

	-- His name sign is keyed by CREATURE id, and he has just been given a new
	-- one. Without this he stands there with a plain name until something else
	-- happens to rebroadcast. Guarded because the network script loads after
	-- this library, and the startup sweep spawns everyone before anyone is
	-- online (Game.getPlayers() is empty then, so this costs nothing).
	if HirelingWindow and HirelingWindow.broadcastSigns then
		HirelingWindow.broadcastSigns()
	end
	return true
end

function Hireling:returnToLamp(playerId)
	if self.active ~= 1 or self._returning then
		return false
	end

	local player = Player(playerId)
	if not player or self:getOwnerId() ~= playerId then
		if player then
			player:getPosition():sendMagicEffect(CONST_ME_POFF)
			player:sendTextMessage(MESSAGE_FAILURE, "You are not the master of this hireling.")
		end
		return false
	end

	self._returning = true
	local hirelingId = self:getId()
	local npcId = self.cid
	addEvent(function(ownerGuid, delayedHirelingId, delayedNpcId)
		local owner = Player(ownerGuid)
		local hireling = getHirelingById(delayedHirelingId)
		if not owner or not hireling then
			if hireling then
				hireling._returning = nil
			end
			return
		end

		local npc = Npc(delayedNpcId)
		local returned, failureReason = persistHirelingReturn(owner, hireling)
		if not returned then
			owner:getPosition():sendMagicEffect(CONST_ME_POFF)
			owner:sendTextMessage(MESSAGE_FAILURE, failureReason)
			hireling._returning = nil
			return
		end

		if npc then
			npc:say("As you wish!", TALKTYPE_PRIVATE_NP, false, owner, npc:getPosition())
			npc:getPosition():sendMagicEffect(CONST_ME_PURPLESMOKE)
			npc:remove()
		end

		hireling._returning = nil
	end, 1000, player:getGuid(), hirelingId, npcId)
	return true
end

function SaveHirelings()
	if not HIRELINGS then
		return true
	end

	for _, hireling in ipairs(HIRELINGS) do
		if not hireling:save() then
			logWarning("[Hireling] Failed to save hireling id " .. tostring(hireling:getId()))
		end
	end
	return true
end

function getHirelingById(id)
	id = tonumber(id)
	if not id then
		return nil
	end

	for _, hireling in ipairs(HIRELINGS) do
		if hireling:getId() == id then
			return hireling
		end
	end
	return nil
end

function getHirelingByPosition(position)
	if not position then
		return nil
	end

	for _, hireling in ipairs(HIRELINGS) do
		if hireling.active == 1 and hireling.posx == position.x and hireling.posy == position.y and hireling.posz == position.z then
			return hireling
		end
	end
	return nil
end

function getHirelingByCid(cid)
	cid = tonumber(cid)
	if not cid then
		return nil
	end

	for _, hireling in ipairs(HIRELINGS) do
		if hireling.cid == cid then
			return hireling
		end
	end
	return nil
end

function GetHirelingSkillNameById(id)
	id = tonumber(id)
	for _, skill in pairs(HIRELING_SKILLS) do
